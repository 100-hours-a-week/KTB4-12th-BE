SELECT
    1 + ((t.n - 1) % 11) AS sender_id,
    1 + ((t.n + 2) % 11) AS recipient_id,
    p.id AS product_id,
    1 + (t.n % 3) AS quantity,
    p.price AS product_price_snapshot,
    p.name AS product_name_snapshot,
    CASE t.n % 10
        WHEN 0 THEN 'PROCESSING'
        WHEN 7 THEN 'FAILED'
        ELSE 'COMPLETED'
    END AS status,
    UUID_TO_BIN(UUID()) AS idempotency_key,
    SHA2(CONCAT('gift-seed-', t.n), 256) AS request_fingerprint,
    DATE_SUB(NOW(), INTERVAL t.n * 17 HOUR) AS completed_at,
    DATE_SUB(NOW(), INTERVAL t.n * 17 HOUR) AS created_at,
    DATE_SUB(NOW(), INTERVAL t.n * 17 HOUR) AS updated_at
FROM (
    SELECT a.d * 4 + b.d + 1 AS n
    FROM (
        SELECT 0 AS d UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3
        UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7
        UNION ALL SELECT 8 UNION ALL SELECT 9
    ) a
    CROSS JOIN (
        SELECT 0 AS d UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3
    ) b
) t
JOIN products p ON p.id = 1 + ((t.n - 1) % 52);

